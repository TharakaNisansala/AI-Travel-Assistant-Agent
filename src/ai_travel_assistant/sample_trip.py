"""Deployment: a prepared sample itinerary that needs no AI at all.

The public demo runs on small free quotas. When they are used up (or a
visitor just wants a quick look), the page can show this sample instead:
the same day cards, cost table, notes and PDF export as a live plan.

What this file demonstrates:
  1. Static data through the same schema. data/sample_trip.json is validated
     as a full schemas.Itinerary, so the cards, the Markdown and the PDF
     render it with the code a live plan uses. If the schema changes, the
     tests fail instead of the demo page.
  2. Honest labelling. Every view of the sample carries SAMPLE_LABEL and
     SAMPLE_NOTE, so it is never mistaken for a live AI answer.
  3. Zero AI calls. This module imports no LLM code and makes no network
     request; it only reads a file that ships with the package.

How the sample was made (by hand, 2026-11-23): every place, price and time
comes from data the project already saved - the Wikivoyage Kandy text and
the OSRM road times in docs/itinerary_checks/kandy.md, and the built-in
destination guide (tools.DESTINATIONS) for Peradeniya. Each fact's quote is
copied word for word from that Wikivoyage text.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

from ai_travel_assistant.itinerary_output import render_itinerary_markdown
from ai_travel_assistant.schemas import Itinerary

SAMPLE_LABEL = "Sample — not live AI"
SAMPLE_NOTE = (
    "This is a prepared example plan, put together and checked by hand from "
    "saved Wikivoyage, OSRM and built-in guide data (2026-11-23). It was not "
    "generated for you by the AI, and viewing it makes no AI requests."
)
SAMPLE_PDF_NOTE = (
    f"{SAMPLE_LABEL}: a prepared example plan, checked by hand from saved "
    "Wikivoyage, OSRM and built-in guide data. Not generated by live AI."
)
# Next to the curated prices (pricing_service.CURATED_FILE); ships with the package.
SAMPLE_FILE = Path(__file__).with_name("data") / "sample_trip.json"


@lru_cache(maxsize=1)
def _sample() -> Itinerary:
    raw = SAMPLE_FILE.read_text(encoding="utf-8")
    return Itinerary.model_validate(json.loads(raw))


def sample_itinerary() -> dict[str, Any]:
    """The sample as the plain dict the cards and the PDF take (a fresh copy).

    The parsed file is cached (it is static and the same for everyone); each
    caller gets its own copy, so no visitor's view can change another's.
    """
    return _sample().model_dump(mode="json")


def sample_markdown() -> str:
    """The plain-text version, labelled as a sample at the top."""
    return f"**{SAMPLE_LABEL}.** {SAMPLE_NOTE}\n\n" + render_itinerary_markdown(
        _sample()
    )
