"""Deployment: the prepared sample trip (data, labels, PDF, no AI). Offline."""

from __future__ import annotations

import socket
import subprocess
import sys
from pathlib import Path

import pytest

from ai_travel_assistant import sample_trip
from ai_travel_assistant.itinerary_pdf import itinerary_pdf
from ai_travel_assistant.schemas import Itinerary
from ai_travel_assistant.tools import DESTINATIONS
from tests.test_itinerary_pdf import pdf_text

# The saved tool results the sample was checked against.
KANDY_CHECK = (
    Path(__file__).parents[1] / "docs" / "itinerary_checks" / "kandy.md"
).read_text(encoding="utf-8")


def plan() -> dict:
    return sample_trip.sample_itinerary()


# --- The data -----------------------------------------------------------------


def test_the_sample_is_a_valid_full_itinerary():
    itinerary = Itinerary.model_validate(plan())
    assert itinerary.destination == "Kandy"
    assert itinerary.days == len(itinerary.day_plans) == 2
    assert [d.day for d in itinerary.day_plans] == [1, 2]
    assert all(d.activities for d in itinerary.day_plans)


def test_every_fact_quote_is_word_for_word_from_the_saved_wikivoyage_text():
    for fact in plan()["facts"]:
        assert fact["source"] == "Wikivoyage"
        assert fact["quote"] in KANDY_CHECK, fact["quote"]


def test_every_place_comes_from_its_named_source():
    kandy = next(d for d in DESTINATIONS if d.name == "Kandy")
    for day in plan()["day_plans"]:
        for activity in day["activities"]:
            if activity["source"] == "Built-in guide":
                assert activity["name"] in kandy.activities
            else:
                assert activity["source"] == "Wikivoyage"
                first = activity["name"].split(" (")[0].lower()
                assert first in KANDY_CHECK.lower(), activity["name"]


def test_road_times_match_the_saved_osrm_results():
    legs = [leg for day in plan()["day_plans"] for leg in day["travel"]]
    assert [(leg["from_place"], leg["to_place"]) for leg in legs] == [
        ("Colombo", "Kandy"),
        ("Kandy", "Peradeniya"),
    ]
    assert (legs[0]["road_distance_km"], legs[0]["driving_minutes"]) == (115, 132)
    assert "115 km" in KANDY_CHECK and "2 hours 12 minutes" in KANDY_CHECK
    assert (legs[1]["road_distance_km"], legs[1]["driving_minutes"]) == (8, 10)
    assert "8 km from Kandy" in KANDY_CHECK and "10 minutes" in KANDY_CHECK


def test_prices_appear_in_the_saved_text_and_no_conversion_is_invented():
    for cost in plan()["costs"]:
        assert cost["amount_usd"] is None  # no live exchange rate in a sample
    assert "2000 to 3500 per ticket" in KANDY_CHECK
    assert "Rs 500 in second class" in KANDY_CHECK


def test_the_sample_admits_what_it_does_not_have():
    sample = plan()
    assert all(day["weather"] is None for day in sample["day_plans"])
    assert any("forecast" in line for line in sample["not_available"])
    assert sample["budget"] is None and sample["stays"] is None
    assert sample["warnings"]  # prices may be out of date


def test_each_caller_gets_its_own_copy():
    first = plan()
    first["destination"] = "Changed by one visitor"
    first["day_plans"].clear()
    assert plan()["destination"] == "Kandy"
    assert len(plan()["day_plans"]) == 2


# --- Labels -------------------------------------------------------------------


def test_the_label_says_sample_not_live_ai():
    assert sample_trip.SAMPLE_LABEL == "Sample — not live AI"
    assert "not generated" in sample_trip.SAMPLE_NOTE
    assert "no AI requests" in sample_trip.SAMPLE_NOTE


def test_the_plain_text_starts_with_the_label():
    text = sample_trip.sample_markdown()
    assert text.startswith(f"**{sample_trip.SAMPLE_LABEL}.**")
    assert "# 2-day trip to Kandy" in text
    assert "Temple of the Tooth" in text


# --- PDF ----------------------------------------------------------------------


def test_the_sample_pdf_is_labelled_on_the_title_and_in_the_footer():
    text = pdf_text(itinerary_pdf(plan(), sample=True))
    assert "SAMPLE — NOT LIVE AI" in text
    assert "Not generated by live AI" in text
    assert "2-day trip to Kandy" in text
    assert "Peradeniya Royal Botanical Gardens" in text


def test_a_live_plan_pdf_carries_no_sample_label():
    text = pdf_text(itinerary_pdf(plan()))
    assert "SAMPLE" not in text and "Not generated by live AI" not in text


# --- No AI, no network ----------------------------------------------------------


def test_showing_the_sample_opens_no_network_connection(monkeypatch):
    def no_network(*args, **kwargs):
        raise AssertionError("the sample tried to use the network")

    monkeypatch.setattr(socket.socket, "connect", no_network)
    monkeypatch.setattr(socket, "create_connection", no_network)
    sample_trip._sample.cache_clear()
    plan()
    sample_trip.sample_markdown()
    itinerary_pdf(plan(), sample=True)


def test_the_sample_loads_no_llm_client_code():
    """Run in a fresh interpreter: nothing LLM-related may be imported."""
    code = (
        "import sys\n"
        "from ai_travel_assistant import sample_trip\n"
        "from ai_travel_assistant.itinerary_pdf import itinerary_pdf\n"
        "itinerary_pdf(sample_trip.sample_itinerary(), sample=True)\n"
        "sample_trip.sample_markdown()\n"
        "bad = ('langchain_google_genai', 'langchain_groq', 'langchain_openai',\n"
        "       'ai_travel_assistant.llm_basics',\n"
        "       'ai_travel_assistant.provider_pool')\n"
        "print(','.join(m for m in bad if m in sys.modules))\n"
    )
    result = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, text=True, check=True
    )
    assert result.stdout.strip() == ""


